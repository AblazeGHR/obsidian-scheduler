function filtersToFrontmatter(filters, defaultDate) {
  const result = {};
  const today = defaultDate;
  const allConds = [];
  for (const clause of filters) {
    if (clause.type === "visual") {
      for (const c3 of clause.conditions) {
        allConds.push(c3);
      }
    }
  }
  for (const f4 of allConds) {
    switch (f4.operator) {
      case "equals":
        result[f4.field] = f4.value;
        break;
      case "contains":
        result[f4.field] = f4.value;
        break;
      case "greater_than": {
        const idx = PRIORITY_SCALE.indexOf(f4.value);
        if (idx >= 0 && idx < PRIORITY_SCALE.length - 1) {
          result[f4.field] = PRIORITY_SCALE[idx + 1];
        } else {
          result[f4.field] = f4.value;
        }
        break;
      }
      case "less_than": {
        const idx = PRIORITY_SCALE.indexOf(f4.value);
        if (idx > 0) {
          result[f4.field] = PRIORITY_SCALE[idx - 1];
        } else {
          result[f4.field] = f4.value;
        }
        break;
      }
      case "before":
      case "after":
        result[f4.field] = today;
        break;
      default:
        result[f4.field] = f4.value;
        break;
    }
  }
  return result;
}
